def collect_files(include_only: list[str] | None = None) -> list[Path]:
    files: list[Path] = []
    for p in sorted(EXPORTS.iterdir()):
        if not p.is_file():
            continue
        if p.suffix not in ALLOWED_SUFFIXES:
            continue
        files.append(p)
    extra = [ROOT / "LICENSE", ROOT / "NOTICE"]
    # license text is large and not needed for most consumers; still include NOTICE
    files = [f for f in files if f.suffix == ".jsonl" or f.suffix == ".parquet" or f.suffix == ".csv" or f.suffix == ".sqlite" or f.name == "checksums.json"]
    files.extend(extra)
    if include_only:
        keep = set(include_only)
        files = [f for f in files if (f.name in keep) or (f.suffix in {".jsonl", ".parquet", ".csv", ".sqlite"} and f.name.split(".")[0] in keep)]
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description="Publish exports/ to the Hugging Face Hub.")
    ap.add_argument("--repo", required=True, help="target dataset repo, e.g. user/large-anime-text-dataset")
    ap.add_argument("--token", default=os.environ.get("HF_TOKEN", ""), help="HF token (default: $HF_TOKEN)")
    ap.add_argument("--dry-run", action="store_true", help="list files to upload without uploading")
    ap.add_argument("--private", action="store_true", help="create a private dataset repo")
    ap.add_argument("--revision", default="main", help="target branch (default: main)")
    ap.add_argument("--include", nargs="*", default=None, help="only these logical names (e.g. anime qa instructions)")
    args = ap.parse_args()

    files = collect_files(args.include)
    if not files:
        print("no files to upload; run `python -m src.cli export` first")
        return 2

    total = sum(p.stat().st_size for p in files)
    print(f"found {len(files)} files, {total/1e6:.1f} MB")
    for p in files:
        print(f"  -> {p.relative_to(ROOT)}")

    if args.dry_run:
        print("dry-run: nothing uploaded")
        return 0

    if not args.token:
        print("error: no token; pass --token or set HF_TOKEN (get one at https://huggingface.co/settings/tokens)")
        return 2

    try:
        from huggingface_hub import HfApi
    except ImportError:
        print('error: missing dependency; run: pip install "huggingface_hub[cli]"')
        return 2

    api = HfApi(token=args.token)
    card = Path(EXPORTS) / "README.md"
    card.write_text(build_card(args.repo), encoding="utf-8")
    files = [card] + files

    try:
        info = api.create_repo(repo_id=args.repo, repo_type="dataset", exist_ok=True, private=args.private)
    except Exception as exc:  # pragma: no cover - network
        print(f"error creating repo: {exc}")
        return 1

    print(f"uploading to {info.repo_id} ({args.revision})…")
    for p in files:
        rel = p.name if p.parent == EXPORTS else p.relative_to(ROOT)
        print(f"  up {rel}")
        api.upload_file(
            path_or_fileobj=str(p),
            path_in_repo=str(rel),
            repo_id=args.repo,
            repo_type="dataset",
            revision=args.revision,
        )

    api.set_dataset_tags(args.repo, ["anime", "llm", "fine-tuning", "qa", "rag"])
    print(f"done: https://huggingface.co/datasets/{args.repo}")
    return 0


if __name__ == "__main__":
    sys.exit(main())